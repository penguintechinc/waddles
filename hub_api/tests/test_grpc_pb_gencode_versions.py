"""Guard against protobuf/grpc gencode newer than the pinned runtime.

Stubs generated by a newer grpcio-tools than the runtime pinned in
``libs/flask_core/requirements.txt`` raise ``VersionError`` at import time and
crash-loop hub-api. This test fails fast in CI instead.
"""

from __future__ import annotations

import importlib
import re
from importlib.metadata import version
from pathlib import Path

import pytest

PB_ROOT = Path(__file__).resolve().parents[1] / "grpc_internal" / "pb"
PB2_FILES = sorted(PB_ROOT.rglob("*_pb2.py"))
GRPC_FILES = sorted(PB_ROOT.rglob("*_pb2_grpc.py"))


def _v(text: str) -> tuple[int, ...]:
    """Parse a dotted version into a comparable tuple, ignoring suffixes."""
    return tuple(int(p) for p in re.findall(r"\d+", text)[:3])


def _module_name(path: Path) -> str:
    """Return the dotted import path of a stub relative to the pb root."""
    return ".".join(path.relative_to(PB_ROOT).with_suffix("").parts)


def test_stub_inventory_not_empty() -> None:
    """A scanner pointed at the wrong root must not report clean."""
    assert len(PB2_FILES) >= 8
    assert len(GRPC_FILES) >= 8


@pytest.mark.parametrize("path", PB2_FILES, ids=lambda p: p.name)
def test_protobuf_gencode_not_newer_than_runtime(path: Path) -> None:
    """Each *_pb2.py declares a gencode version <= the installed protobuf."""
    m = re.search(r"# Protobuf Python Version: (\S+)", path.read_text())
    assert m, f"{path.name}: missing gencode header"
    assert _v(m.group(1)) <= _v(
        version("protobuf")
    ), f"{path.name}: gencode {m.group(1)} > runtime protobuf {version('protobuf')}"


@pytest.mark.parametrize("path", GRPC_FILES, ids=lambda p: p.name)
def test_grpc_gencode_not_newer_than_runtime(path: Path) -> None:
    """Each *_pb2_grpc.py declares GRPC_GENERATED_VERSION <= installed grpcio."""
    m = re.search(r"GRPC_GENERATED_VERSION = [\"']([^\"']+)[\"']", path.read_text())
    assert m, f"{path.name}: missing GRPC_GENERATED_VERSION"
    assert _v(m.group(1)) <= _v(
        version("grpcio")
    ), f"{path.name}: gencode {m.group(1)} > runtime grpcio {version('grpcio')}"


@pytest.mark.parametrize("path", PB2_FILES + GRPC_FILES, ids=lambda p: p.name)
def test_stub_imports(path: Path) -> None:
    """Every generated module imports cleanly against the installed runtime."""
    importlib.import_module(_module_name(path))
