def _openssl(*args: str, cwd: Path) -> None:
    subprocess.run(["openssl", *args], cwd=cwd, check=True, capture_output=True)  # noqa: S603,S607


def _make_ca(directory: Path, name: str) -> tuple[Path, Path, Path]:
    """CA + a server cert for 127.0.0.1/localhost signed by it; returns (ca, cert, key)."""
    directory.mkdir(parents=True, exist_ok=True)
    ec = ["-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes"]
    _openssl(
        "req", "-x509", *ec, "-keyout", f"{name}-ca.key", "-out", f"{name}-ca.pem", "-days", "2",
        "-subj", f"/CN={name}-ca", "-addext", "basicConstraints=critical,CA:TRUE",
        "-addext", "keyUsage=critical,keyCertSign", cwd=directory,
    )  # fmt: skip
    _openssl(
        "req", *ec, "-keyout", f"{name}.key", "-out", f"{name}.csr", "-subj", "/CN=localhost",
        cwd=directory,
    )  # fmt: skip
    (directory / f"{name}.ext").write_text("subjectAltName=IP:127.0.0.1,DNS:localhost\n")
    _openssl(
        "x509", "-req", "-in", f"{name}.csr", "-CA", f"{name}-ca.pem", "-CAkey", f"{name}-ca.key",
        "-CAcreateserial", "-out", f"{name}.pem", "-days", "2", "-extfile", f"{name}.ext",
        cwd=directory,
    )  # fmt: skip
    return directory / f"{name}-ca.pem", directory / f"{name}.pem", directory / f"{name}.key"


