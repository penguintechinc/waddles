class TestRetryPolicy:
    async def test_transient_4xx_retries_with_backoff_then_succeeds(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any, caplog: pytest.LogCaptureFixture
    ) -> None:
        caplog.set_level(logging.DEBUG)
        sink = make_sink()
        sink.handler.script = ["451 try later", "451 again", "250 OK"]
        smtp_env(sink)
        assert (await _public_submit(client, email=REQUESTER)).status_code == 202
        assert sink.handler.data_attempts == 3 and len(sink.handler.messages) == 1
        retries = [r for r in caplog.records if r.getMessage() == "dsar.email.retry"]
        assert [r.__dict__["attempt"] for r in retries] == [1, 2]
        assert all(
            r.__dict__["reason"] == "smtp_4xx" and r.__dict__["code"] == 451 for r in retries
        )
        assert E.VERIFICATION_SENT in [E(e.event_type) for e in _events(db)]

    async def test_transient_exhausted_records_failure_after_max_retries(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any
    ) -> None:
        sink = make_sink()
        sink.handler.script = ["451 busy"] * 10
        smtp_env(sink, DSAR_SMTP_MAX_RETRIES="2")
        assert (await _public_submit(client, email=REQUESTER)).status_code == 202
        assert sink.handler.data_attempts == 3 and sink.handler.messages == []
        assert _reasons(db) == ["smtp_4xx"]

    async def test_permanent_5xx_is_not_retried(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any
    ) -> None:
        sink = make_sink()
        sink.handler.script = ["554 rejected"] * 5
        smtp_env(sink)
        assert (await _public_submit(client, email=REQUESTER)).status_code == 202
        assert sink.handler.data_attempts == 1 and _reasons(db) == ["smtp_5xx"]
        assert _rows(db)[0].status == int(S.VERIFICATION_PENDING)

    async def test_connection_refused_retries_then_fails(
        self, client: Any, db: Any, smtp_env: Any, caplog: pytest.LogCaptureFixture
    ) -> None:
        caplog.set_level(logging.DEBUG)
        smtp_env(None, DSAR_SMTP_MAX_RETRIES="1")  # nothing listens on this port
        assert (await _public_submit(client, email=REQUESTER)).status_code == 202
        assert _reasons(db) == ["connect"]
        assert len([r for r in caplog.records if r.getMessage() == "dsar.email.retry"]) == 1

    async def test_unresponsive_server_times_out(self, client: Any, db: Any, smtp_env: Any) -> None:
        async def silent(_r: asyncio.StreamReader, _w: asyncio.StreamWriter) -> None:
            await asyncio.sleep(30)

        server = await asyncio.start_server(silent, "127.0.0.1", 0)
        port = server.sockets[0].getsockname()[1]
        try:
            smtp_env(
                None,
                DSAR_SMTP_PORT=str(port),
                DSAR_SMTP_CONNECT_TIMEOUT="0.5",
                DSAR_SMTP_MAX_RETRIES="0",
            )
            assert (await _public_submit(client, email=REQUESTER)).status_code == 202
        finally:
            server.close()
        assert _reasons(db) == ["timeout"]

    async def test_response_is_identical_on_success_and_on_every_failure(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any
    ) -> None:
        """Uniform 202: the requester cannot tell delivered / failed / unconfigured apart."""
        bodies = []
        sink = make_sink()
        smtp_env(sink)
        bodies.append(await (await _public_submit(client, email="a1@example.org")).get_json())
        sink.handler.script = ["554 no"]
        bodies.append(await (await _public_submit(client, email="a2@example.org")).get_json())
        smtp_env(None)  # refused
        bodies.append(await (await _public_submit(client, email="a3@example.org")).get_json())
        smtp_env(sink, DSAR_SMTP_HOST="")  # unconfigured
        resp = await _public_submit(client, email="a4@example.org")
        assert resp.status_code == 202
        bodies.append(await resp.get_json())
        assert all(b == bodies[0] for b in bodies)


