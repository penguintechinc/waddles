class TestPiiAndTelemetry:
    async def test_no_pii_in_logs_for_success_retry_and_every_failure_path(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any, caplog: pytest.LogCaptureFixture
    ) -> None:
        # regression: aiosmtplib echoes the server's reply text (which often contains the
        # recipient address) in its exception message; the service logs with exc_info, so the
        # sender must re-raise sanitised (`from None`), or the address lands in the log.
        caplog.set_level(logging.DEBUG)
        sink = make_sink()
        smtp_env(sink)
        await _public_submit(client, email=REQUESTER)  # success
        sink.handler.script = ["451 mailbox zelda.requester@example.org busy", "250 OK"]
        await _public_submit(client, email="zelda.requester+2@example.org")  # retry then ok
        sink.handler.rcpt_script = ["550 5.1.1 <zelda.requester+3@example.org> user unknown"]
        await _public_submit(client, email="zelda.requester+3@example.org")  # permanent, echoed
        smtp_env(None, DSAR_SMTP_HOST="")
        await _public_submit(client, email="zelda.requester+4@example.org")  # unconfigured
        blob = _leak_blob(caplog)
        assert "zelda" not in blob and "example.org" not in blob.replace("app.example", "")
        assert "token=" not in blob
        assert any(
            r.getMessage() == "dsar.email.attempt" and getattr(r, "recipient_fp", "")
            for r in caplog.records
        )
        assert _reasons(db).count("smtp_5xx") == 1

    async def test_metrics_carry_bounded_outcome_labels_and_no_pii(
        self, client: Any, make_sink: Any, smtp_env: Any, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        class Rec:
            def __init__(self) -> None:
                self.calls: list[tuple[float, dict[str, str]]] = []

            def add(self, n: float, attrs: dict[str, str]) -> None:
                self.calls.append((n, attrs))

            record = add

        sends, retries, durations = Rec(), Rec(), Rec()
        monkeypatch.setattr(telemetry, "email_sends", sends)
        monkeypatch.setattr(telemetry, "email_retries", retries)
        monkeypatch.setattr(telemetry, "email_duration", durations)
        sink = make_sink()
        smtp_env(sink)
        sink.handler.script = ["451 later", "250 OK"]
        await _public_submit(client, email=REQUESTER)
        sink.handler.script = ["550 no"]
        await _public_submit(client, email="other.one@example.org")
        assert [a for _, a in sends.calls] == [{"outcome": "sent"}, {"outcome": "failed_permanent"}]
        assert [a for _, a in retries.calls] == [{"reason": "smtp_4xx"}]
        assert len(durations.calls) == 2 and all(v >= 0 for v, _ in durations.calls)
        assert "zelda" not in repr(sends.calls + retries.calls + durations.calls)

