def _body_text(message: email.message.EmailMessage) -> str:
    part = message.get_body(preferencelist=("plain",))
    assert part is not None
    return str(part.get_content())


def _token_of(message: email.message.EmailMessage) -> str:
    found = re.search(r"#token=([A-Za-z0-9_-]+)", _body_text(message))
    assert found, _body_text(message)
    return found.group(1)


def _reasons(db_: Any) -> list[str]:
    import json as _json

    out = []
    for ev in _events(db_):
        if svc.EventType(ev.event_type) == E.VERIFICATION_SEND_FAILED:
            detail = ev.detail
            out.append((_json.loads(detail) if isinstance(detail, str) else detail)["reason"])
    return out


def _leak_blob(caplog: pytest.LogCaptureFixture) -> str:
    """Everything the APP logged (the sink's own `mail.log` echoes the address by design)."""
    records = [r for r in caplog.records if r.name.startswith("services")]
    fmt = logging.Formatter()
    return "\n".join(fmt.format(r) + repr(r.__dict__) for r in records)


