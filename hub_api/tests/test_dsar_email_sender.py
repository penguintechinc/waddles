def _server_ctx(cert: Path, key: Path) -> ssl.SSLContext:
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(cert, key)
    return ctx


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


class _Handler:
    """Records mail; `script` / `rcpt_script` inject per-attempt SMTP replies."""

    def __init__(self) -> None:  # noqa: D107
        self.messages: list[Any] = []
        self.ehlo = 0
        self.data_attempts = 0
        self.ehlo_names: list[str] = []
        self.script: list[str] = []
        self.rcpt_script: list[str] = []

    async def handle_EHLO(
        self, server: Any, session: Any, envelope: Any, hostname: str, responses: list[str]
    ) -> list[str]:  # noqa: E501,N802
        self.ehlo += 1
        self.ehlo_names.append(hostname)
        session.host_name = hostname  # aiosmtpd's new-style hook owns this
        return responses

    async def handle_RCPT(
        self, server: Any, session: Any, envelope: Any, address: str, rcpt_options: Any
    ) -> str:  # noqa: E501,N802
        if self.rcpt_script:
            return self.rcpt_script.pop(0)
        envelope.rcpt_tos.append(address)
        return "250 OK"

    async def handle_DATA(self, server: Any, session: Any, envelope: Any) -> str:  # noqa: N802
        self.data_attempts += 1
        if self.script:
            reply = self.script.pop(0)
            if reply != "250 OK":
                return reply
        self.messages.append(envelope)
        return "250 OK"


class Sink:
    """One running aiosmtpd controller plus its handler."""

    def __init__(self, handler: _Handler, controller: Controller, port: int) -> None:  # noqa: D107
        self.handler, self.controller, self.port = handler, controller, port

    def mail(self, index: int = -1) -> email.message.EmailMessage:
        """Parse a received message with the modern policy."""
        parsed = email.message_from_bytes(
            self.handler.messages[index].original_content, policy=policy.default
        )
        assert isinstance(parsed, email.message.EmailMessage)
        return parsed


@pytest.fixture
def make_sink(pki: dict[str, Path]) -> Iterator[Any]:
    """Factory: `make_sink(mode="starttls"|"tls"|"plain", auth=None, cert="cert"|"rogue_cert")`."""
    started: list[Controller] = []

    def factory(
        *, mode: str = "starttls", auth: tuple[str, str] | None = None, cert: str = "cert"
    ) -> Sink:
        handler = _Handler()
        port = _free_port()
        key = pki["rogue_key" if cert == "rogue_cert" else "key"]
        ctx = _server_ctx(pki[cert], key)
        kwargs: dict[str, Any] = {}
        if mode == "starttls":
            kwargs.update(tls_context=ctx, require_starttls=True)
        elif mode == "tls":
            kwargs.update(ssl_context=ctx)
        if auth is not None:

            def check(
                server: Any, session: Any, envelope: Any, mechanism: str, data: Any
            ) -> AuthResult:
                ok = (
                    isinstance(data, LoginPassword)
                    and data.login == auth[0].encode()
                    and data.password == auth[1].encode()
                )
                return AuthResult(success=ok, handled=False)

            kwargs.update(authenticator=check, auth_required=True, auth_require_tls=mode != "plain")
        controller = Controller(handler, hostname="127.0.0.1", port=port, **kwargs)
        controller.start()
        started.append(controller)
        return Sink(handler, controller, port)

    yield factory
    for controller in started:
        controller.stop()


