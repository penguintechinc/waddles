class TestEndToEnd:
    async def test_public_submit_delivers_real_mail_and_token_verifies_once(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any
    ) -> None:
        sink = make_sink(mode="starttls")
        smtp_env(sink)
        response = await _public_submit(client, email=REQUESTER)
        assert response.status_code == 202
        assert len(sink.handler.messages) == 1
        envelope = sink.handler.messages[0]
        assert envelope.rcpt_tos == [REQUESTER] and envelope.mail_from == "privacy@waddles.example"
        msg = sink.mail()
        assert msg["Subject"] == sender.SUBJECT and msg["To"] == REQUESTER
        assert msg["From"] == "Waddles Privacy <privacy@waddles.example>"
        assert msg["Auto-Submitted"] == "auto-generated"
        assert msg["Message-ID"].endswith("@waddles.example>") and msg["Date"]
        # multipart/alternative: text + simple HTML, same link in both, no tracking
        assert msg.get_content_type() == "multipart/alternative"
        assert [p.get_content_type() for p in msg.iter_parts()] == ["text/plain", "text/html"]
        link = f"https://app.example/privacy/verify?tenant={TENANT_SLUG}#token={_token_of(msg)}"
        html_part = msg.get_body(preferencelist=("html",))
        assert html_part is not None and link in html_part.get_content()
        assert link in _body_text(msg)
        for needle in ("<img", "pixel", "utm_", "track"):
            assert needle not in html_part.get_content().lower()
        assert "ignore this email" in _body_text(msg) and "expires in" in _body_text(msg)
        assert TENANT_SLUG not in msg["Subject"] and "Acme" not in _body_text(msg)
        # DB state + event, then the emailed token works exactly once
        assert _rows(db)[0].status == int(S.VERIFICATION_PENDING)
        assert E.VERIFICATION_SENT in [E(e.event_type) for e in _events(db)]
        token = _token_of(msg)
        assert (await client.post(f"{PUB}/verify", json={"token": token})).status_code == 200
        assert _rows(db)[0].status == int(S.VERIFIED)
        assert (await client.post(f"{PUB}/verify", json={"token": token})).status_code == 400

    async def test_resend_sends_a_new_mail_with_a_new_token(
        self, client: Any, db: Any, make_sink: Any, smtp_env: Any
    ) -> None:
        sink = make_sink()
        smtp_env(sink)
        await _public_submit(client, email=REQUESTER)
        first = _token_of(sink.mail())
        body = {"email": REQUESTER, "requestType": 1, "captchaToken": solve_altcha()}
        assert (await client.post(RESEND, json=body)).status_code == 202
        assert len(sink.handler.messages) == 2
        second = _token_of(sink.mail())
        assert second != first
        assert f"tenant={TENANT_SLUG}#token={second}" in _body_text(sink.mail())
        assert (await client.post(f"{PUB}/verify", json={"token": first})).status_code == 400
        assert (await client.post(f"{PUB}/verify", json={"token": second})).status_code == 200
        assert E.VERIFICATION_RESENT in [E(e.event_type) for e in _events(db)]


