"""Helm render assertions for the platform-secret S3 escrow identity (hub_api T7).

The escrow bucket is reachable ONLY by the dedicated `hub-api-escrow` SeaweedFS identity: no other
identity (bundle executor, precompiler, streaming, bundle storage, the general hub-api identity)
names the bucket, its credentials live in their own Secret (never the envFrom'd `waddlebot-secrets`)
generated at RUNTIME by the provision-secrets hook, and only SeaweedFS and hub-api reference them.
Zero identities / documents / matches is a hard failure.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest
import yaml
from provision_harness import spec_keys, with_provisioned  # type: ignore[import-not-found]

_CHART = Path(__file__).resolve().parents[1]
_BUCKET = "waddles-platform-escrow"
_SECRET_SUFFIX = "-platform-escrow-s3"
_KEYS = {"ESCROW_S3_ACCESS_KEY_ID", "ESCROW_S3_SECRET_ACCESS_KEY"}


def _render(*sets: str, values: str = "values-alpha.yaml") -> list[dict[str, Any]]:
    argv = [
        "helm", "template", "waddlebot", str(_CHART), "--kube-version", "1.30.0",
        "--values", str(_CHART / values),
    ]  # fmt: skip
    for s in sets:
        argv += ["--set", s]
    out = subprocess.run(argv, capture_output=True, text=True, check=False)
    if out.returncode != 0:
        pytest.fail(f"helm template failed:\n{out.stderr}")
    docs = [d for d in yaml.safe_load_all(out.stdout) if d]
    assert docs, "helm template produced zero documents"
    return with_provisioned(docs)


@pytest.fixture(scope="module")
def helm_available() -> None:
    if not shutil.which("helm"):
        pytest.skip("helm CLI not available")


def _seaweed(docs: list[dict[str, Any]]) -> dict[str, Any]:
    found = [
        d
        for d in docs
        if d.get("kind") == "Deployment" and d["metadata"]["name"] == "seaweedfs"
    ]
    assert len(found) == 1, "expected exactly one seaweedfs Deployment"
    return found[0]


def _identities(docs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """The rendered s3-identities.json (heredoc inside the seaweedfs container command)."""
    script = _seaweed(docs)["spec"]["template"]["spec"]["containers"][0]["command"][-1]
    match = re.search(r"<<EOF\n(.*?)\n\s*EOF", script, re.S)
    assert match, "no s3-identities heredoc rendered"
    body = "\n".join(line.strip() for line in match.group(1).splitlines())
    identities = json.loads(body)["identities"]
    assert identities, "zero identities rendered"
    return identities


def test_only_the_escrow_identity_names_the_escrow_bucket(helm_available: None) -> None:
    identities = _identities(_render())
    named = {
        i["name"]: i["actions"]
        for i in identities
        if any(_BUCKET in a for a in i["actions"])
    }
    assert list(named) == ["hub-api-escrow"], named
    assert sorted(named["hub-api-escrow"]) == sorted(
        f"{verb}:{_BUCKET}" for verb in ("Read", "Write", "List")
    )
    # no wildcard / admin / prefix-less grant on any other identity could reach it either
    for ident in identities:
        if ident["name"] in {"hub-api-escrow", "bucket-init"}:
            continue
        for action in ident["actions"]:
            assert action not in {"Admin", "Read", "Write", "List", "Tagging"}, ident[
                "name"
            ]
            assert "*" not in action, ident["name"]


def test_escrow_identity_is_in_no_bundle_or_general_hub_api_grant(
    helm_available: None,
) -> None:
    for ident in _identities(_render()):
        if ident["name"] == "hub-api":
            assert not any(_BUCKET in a for a in ident["actions"])
        if ident["name"].startswith(("svc-bundles", "bundle-storage", "svc-streaming")):
            assert not any(_BUCKET in a for a in ident["actions"]), ident["name"]


def test_escrow_credentials_are_runtime_generated_in_their_own_secret(
    helm_available: None,
) -> None:
    docs = _render()
    keys = {n: ks for n, ks in spec_keys(docs).items() if n.endswith(_SECRET_SUFFIX)}
    assert len(keys) == 1, keys
    assert set(next(iter(keys.values()))) == _KEYS
    # generated by the hook (harness ran the real script): present, non-placeholder, no template-time lookup
    provisioned = [
        d
        for d in docs
        if d.get("x-provisioned") and d["metadata"]["name"].endswith(_SECRET_SUFFIX)
    ]
    assert len(provisioned) == 1
    data = provisioned[0]["stringData"]
    assert set(data) == _KEYS and all(len(v) >= 16 for v in data.values())
    assert not any(
        d.get("kind") == "Secret"
        and not d.get("x-provisioned")
        and d["metadata"]["name"].endswith(_SECRET_SUFFIX)
        for d in docs
    ), "the escrow Secret must not be rendered by Helm (template-time generation)"


def test_escrow_keys_never_reach_the_envfrom_secret(helm_available: None) -> None:
    docs = _render()
    for d in docs:
        if d.get("kind") == "Secret" and d["metadata"]["name"] == "waddlebot-secrets":
            assert not (set(d.get("stringData") or {}) & _KEYS)
    for name, ks in spec_keys(docs).items():
        if not name.endswith(_SECRET_SUFFIX):
            assert not (set(ks) & _KEYS), name


def test_only_seaweedfs_and_hub_api_mount_the_escrow_secret(
    helm_available: None,
) -> None:
    docs = _render()
    referencing: set[str] = set()
    for d in docs:
        if d.get("kind") not in {
            "Deployment",
            "StatefulSet",
            "Job",
            "CronJob",
            "DaemonSet",
        }:
            continue
        text = yaml.safe_dump(d)
        if _SECRET_SUFFIX in text or "ESCROW_S3" in text or "PLATFORM_ESCROW" in text:
            referencing.add(d["metadata"]["name"])
    assert referencing, "nothing references the escrow Secret"
    assert all(
        n == "seaweedfs" or "hub-api" in n or n.endswith("-provision-secrets")
        for n in referencing
    ), referencing
    assert any("hub-api" in n for n in referencing) and "seaweedfs" in referencing
    for d in docs:
        pod = (d.get("spec") or {}).get("template", {}).get("spec", {})
        for c in pod.get("containers", []) + pod.get("initContainers", []):
            for ef in c.get("envFrom", []):
                assert _SECRET_SUFFIX not in (ef.get("secretRef") or {}).get("name", "")


def test_hub_api_gets_bucket_and_identity_via_secret_refs(helm_available: None) -> None:
    docs = _render()
    envs: dict[str, dict[str, Any]] = {}
    for d in docs:
        if d.get("kind") == "Deployment" and "hub-api" in d["metadata"]["name"]:
            for c in d["spec"]["template"]["spec"]["containers"]:
                envs.update({e["name"]: e for e in c.get("env", [])})
    assert envs, "no hub-api container rendered"
    assert envs["PLATFORM_ESCROW_S3_BUCKET"]["value"] == _BUCKET
    for var, key in (
        ("PLATFORM_ESCROW_S3_ACCESS_KEY_ID", "ESCROW_S3_ACCESS_KEY_ID"),
        ("PLATFORM_ESCROW_S3_SECRET_ACCESS_KEY", "ESCROW_S3_SECRET_ACCESS_KEY"),
    ):
        assert "value" not in envs[var]
        ref = envs[var]["valueFrom"]["secretKeyRef"]
        assert ref["key"] == key and ref["name"].endswith(_SECRET_SUFFIX)


def test_bucket_init_creates_and_versions_the_escrow_bucket(
    helm_available: None,
) -> None:
    docs = _render()
    scripts = [
        c["command"][-1]
        for d in docs
        if d.get("kind") == "Job" and "bucket-init" in d["metadata"]["name"]
        for c in d["spec"]["template"]["spec"]["containers"]
    ]
    assert len(scripts) == 1, "expected exactly one bucket-init Job"
    assert f'"{_BUCKET}"' in scripts[0]
    assert "put-bucket-versioning" in scripts[0] and "Status=Enabled" in scripts[0]
    off = _render("infrastructure.seaweedfs.escrow.versioning=false")
    assert "put-bucket-versioning" not in next(
        c["command"][-1]
        for d in off
        if d.get("kind") == "Job" and "bucket-init" in d["metadata"]["name"]
        for c in d["spec"]["template"]["spec"]["containers"]
    )


def test_every_tier_renders_the_escrow_identity(helm_available: None) -> None:
    sse = "infrastructure.seaweedfs.encryption.secretName=seaweedfs-sse-kek"
    for values in ("values-alpha.yaml", "values-dal2alpha.yaml", "values-beta.yaml"):
        names = {i["name"] for i in _identities(_render(sse, values=values))}
        assert "hub-api-escrow" in names, values
